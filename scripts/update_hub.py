#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import json
import re
import unicodedata
from pathlib import Path

try:
    from docx import Document
    from docx.document import Document as DocumentType
    from docx.table import Table
    from docx.text.paragraph import Paragraph
    from openpyxl import load_workbook
    from pypdf import PdfReader
except ImportError as error:
    raise SystemExit(
        "Missing dependency. Run: python3 -m pip install -r requirements-hub.txt"
    ) from error


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "hub_manifest.json"

def source_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def generated_marker(source: Path) -> str:
    return f"<!-- Generated by scripts/update_hub.py; source-sha256: {source_hash(source)} -->"


def clean_text(value: object) -> str:
    if value is None:
        return ""
    text = unicodedata.normalize("NFC", str(value))
    text = text.replace("\x00", "").replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def md_cell(value: object) -> str:
    return clean_text(value).replace("|", "\\|").replace("\n", "<br>") or " "


def write_output(path: Path, parts: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")


def pdf_to_markdown(source: Path, destination: Path, title: str) -> None:
    reader = PdfReader(str(source))
    ocr_path = source.with_suffix(".ocr.json")
    ocr = None
    if ocr_path.exists():
        ocr = json.loads(ocr_path.read_text(encoding="utf-8"))
        if ocr["source_sha256"] != source_hash(source) or len(ocr["pages"]) != len(reader.pages):
            raise SystemExit(f"Stale or invalid OCR sidecar: {ocr_path}")
    parts = [
        generated_marker(source),
        "",
        f"# {title}",
        "",
        f"**Original source:** `{source.name}`",
        "",
        f"**Pages:** {len(reader.pages)}",
        "",
        "> This Markdown version preserves the extractable text page by page. Consult the original PDF for diagrams, visual composition, and exact pagination.",
        "",
    ]
    if ocr is not None:
        parts.extend(["> Extracción directa complementada con OCR (Apple Vision, español e inglés) en páginas sin texto suficiente. Puede contener errores en fórmulas, tablas y orden de lectura. Verificar el PDF original antes de aplicar sus valores o formatos.", ""])
    for number, page in enumerate(reader.pages, 1):
        text = clean_text(page.extract_text() or "")
        if ocr is not None and len(text) < 100:
            text = clean_text(ocr["pages"][number - 1])
        parts.extend([f"## Page {number}", "", text or "_[No extractable text]_", ""])
    write_output(destination, parts)


def iter_doc_blocks(parent: DocumentType):
    for child in parent.element.body.iterchildren():
        if child.tag.endswith("}p"):
            yield Paragraph(child, parent)
        elif child.tag.endswith("}tbl"):
            yield Table(child, parent)


def table_to_markdown(table: Table) -> list[str]:
    rows = [[md_cell(cell.text) for cell in row.cells] for row in table.rows]
    if not rows:
        return []
    width = max(len(row) for row in rows)
    rows = [row + [" "] * (width - len(row)) for row in rows]
    output = ["| " + " | ".join(rows[0]) + " |", "| " + " | ".join(["---"] * width) + " |"]
    output.extend("| " + " | ".join(row) + " |" for row in rows[1:])
    return output


def docx_to_markdown(source: Path, destination: Path, title: str) -> None:
    document = Document(source)
    parts = [
        generated_marker(source),
        "",
        f"# {title}",
        "",
        f"**Original source:** `{source.name}`",
        "",
        "> This Markdown version preserves paragraphs and tables. Consult the original Word document for exact formatting and pagination.",
        "",
    ]
    table_number = 0
    for block in iter_doc_blocks(document):
        if isinstance(block, Paragraph):
            text = clean_text(block.text)
            if not text:
                continue
            style = (block.style.name or "") if block.style else ""
            heading = re.match(r"Heading\s+(\d+)", style, flags=re.IGNORECASE)
            if heading:
                parts.extend([f"{'#' * min(int(heading.group(1)) + 1, 6)} {text}", ""])
            elif "List Bullet" in style:
                parts.append(f"- {text}")
            elif "List Number" in style:
                parts.append(f"1. {text}")
            else:
                parts.extend([text, ""])
        else:
            table_number += 1
            parts.extend([f"### Table {table_number}", "", *table_to_markdown(block), ""])
    write_output(destination, parts)


def excel_value(value: object) -> str:
    if value is None:
        return ""
    if hasattr(value, "isoformat"):
        try:
            return value.isoformat()
        except TypeError:
            pass
    return clean_text(value).replace("\t", " ").replace("\n", " / ")


def workbook_to_markdown(source: Path, destination: Path, title: str) -> None:
    workbook = load_workbook(source, data_only=False, read_only=False)
    parts = [
        generated_marker(source),
        "",
        f"# {title}",
        "",
        f"**Original source:** `{source.name}`",
        "",
        "> Sheets are represented as tab-separated blocks to preserve wide schedules, formulas, and blank cells. Consult the original workbook for formatting, charts, and calculated display values.",
        "",
    ]
    for sheet in workbook.worksheets:
        parts.extend([f"## Sheet: {sheet.title}", "", "```tsv"])
        for row in sheet.iter_rows(min_row=1, max_row=sheet.max_row, min_col=1, max_col=sheet.max_column):
            values = [excel_value(cell.value) for cell in row]
            while values and not values[-1]:
                values.pop()
            parts.append("\t".join(values))
        parts.extend(["```", ""])
    write_output(destination, parts)


CONVERTERS = {
    "pdf": pdf_to_markdown,
    "docx": docx_to_markdown,
    "xlsx": workbook_to_markdown,
}


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate the DPI hub Markdown knowledge layer.")
    parser.add_argument("--changed-only", action="store_true", help="Only regenerate outputs older than their source.")
    args = parser.parse_args()

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    converted = 0
    skipped = 0
    for item in manifest["documents"]:
        source = ROOT / item["source"]
        output = ROOT / item["output"]
        if not source.exists():
            raise SystemExit(f"Missing source: {source.relative_to(ROOT)}")
        if args.changed_only and output.exists() and output.stat().st_mtime >= source.stat().st_mtime:
            skipped += 1
            continue
        converter = CONVERTERS.get(item["type"])
        if converter is None:
            raise SystemExit(f"Unsupported type: {item['type']}")
        converter(source, output, item["title"])
        print(f"updated {output.relative_to(ROOT)}")
        converted += 1
    print(f"done: {converted} updated, {skipped} unchanged")


if __name__ == "__main__":
    main()
